#!/usr/bin/env python3
"""Builds fanflow.plg, a self-contained Unraid plugin file.

Every plugin file is written by a bash heredoc inside the .plg, so installing needs no download.

    python3 plugin/build.py [version]

The version defaults to the current date and time: Unraid only installs a version newer than the
one installed and compares versions as text.
"""
import datetime
import os
import pathlib
import sys
from xml.sax.saxutils import escape

NAME = "fanflow"
AUTHOR = os.environ.get("FANFLOW_AUTHOR", "R0m1k3")
# GitHub repository "owner/name" the .plg is published from. Unraid's Plugins page downloads
# fanflow.plg from its main branch to check for updates, so commit the rebuilt .plg there.
# FANFLOW_REPO="" builds a .plg without update address (for a fork or a local test).
REPO = os.environ.get("FANFLOW_REPO", "R0m1k3/FanFlow")
MIN_UNRAID = "7.0.0"
EMHTTP = f"/usr/local/emhttp/plugins/{NAME}"
CONFIG = f"/boot/config/plugins/{NAME}"
RC = "/etc/rc.d/rc.fanflow"
DELIMITER = "FANFLOW_EOF"
EXECUTABLE = {"scripts/fanflowd", "scripts/rc.fanflow"}

root = pathlib.Path(__file__).resolve().parent
src = root / "src"
version = sys.argv[1] if len(sys.argv) > 1 else datetime.datetime.now().strftime("%Y.%m.%d.%H%M")
files = {str(path.relative_to(src)): path for path in sorted(src.rglob("*")) if path.is_file()}

install = [
    # An update: stop the running version first (it hands the fans back to the BIOS).
    f"[ -x {RC} ] && {RC} stop >/dev/null 2>&1",
    f"rm -rf {EMHTTP}",
    "mkdir -p " + " ".join(sorted({f"{EMHTTP}/{pathlib.PurePosixPath(t).parent}".rstrip("/.") for t in files} | {CONFIG})),
]
for target, path in sorted(files.items()):
    text = path.read_text(encoding="utf-8").replace("@@VERSION@@", version)
    if not text.endswith("\n"):
        text += "\n"
    for forbidden in ("]]>", DELIMITER):
        if forbidden in text:
            sys.exit(f"{path}: contains {forbidden!r}, which would break the .plg")
    install.append(f"cat > {EMHTTP}/{target} <<'{DELIMITER}'\n{text}{DELIMITER}")

install += [
    f"find {EMHTTP} -type d -exec chmod 755 {{}} +",
    f"find {EMHTTP} -type f -exec chmod 644 {{}} +",
    *[f"chmod 755 {EMHTTP}/{f}" for f in sorted(EXECUTABLE)],
    f"cp {EMHTTP}/scripts/rc.fanflow {RC} && chmod 755 {RC}",
    f"{RC} start",
    'echo ""',
    f'echo "FanFlow {version} is installed."',
    'echo "The first start detects the fans: each one speeds up to full for a few seconds."',
    'echo "Settings: Settings > User Utilities > FanFlow. Dashboard: the FanFlow tile."',
    'echo ""',
]

urls = ""
if REPO:
    urls = (
        f'\n        pluginURL="https://raw.githubusercontent.com/{REPO}/main/{NAME}.plg"'
        f'\n        support="https://github.com/{REPO}/issues"'
    )

changes = (root / "CHANGES.md").read_text(encoding="utf-8").strip().replace("@@VERSION@@", version)

plg = f"""<?xml version='1.0' standalone='yes'?>
<!DOCTYPE PLUGIN>

<PLUGIN name="{NAME}"
        author="{escape(AUTHOR)}"
        version="{version}"
        launch="Settings/FanFlow"{urls}
        icon="icon-fan"
        min="{MIN_UNRAID}">

<CHANGES>
{escape(changes)}
</CHANGES>

<!-- Install: write all plugin files, then start the service. Generated by plugin/build.py; edit the sources, not this file. -->
<FILE Run="/bin/bash">
<INLINE>
<![CDATA[
{chr(10).join(install)}
]]>
</INLINE>
</FILE>

<!-- Remove: stop the service (the BIOS drives the fans again), delete the files and the settings. -->
<FILE Run="/bin/bash" Method="remove">
<INLINE>
<![CDATA[
[ -x {RC} ] && {RC} stop
rm -f {RC}
rm -rf {EMHTTP}
rm -rf /var/local/fanflow
rm -rf {CONFIG}
echo ""
echo "FanFlow has been removed. The BIOS drives the fans again."
echo ""
]]>
</INLINE>
</FILE>

</PLUGIN>
"""

out = root.parent / f"{NAME}.plg"
out.write_text(plg, encoding="utf-8")
print(f"wrote {out} ({len(plg)} bytes, {len(files)} files, version {version})")
